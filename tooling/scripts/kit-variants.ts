/**
 * Writes the dashboard kit's variant registry from the raw ReUI examples in packages/ui/src/variants
 * (files named c-<component>-<n>.tsx, each exporting `Pattern`). Run after installing or removing
 * examples: pnpm --filter @smartapp/tooling kit-variants. tooling/kit-examples.test.ts fails when the
 * registry and the folder disagree.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const repoRoot = resolve(import.meta.dirname, '../..');
const variantsDir = join(repoRoot, 'packages/ui/src/variants');
const target = join(repoRoot, 'apps/dashboard/src/features/kit/kit-variants-registry.ts');

export function listExamples(): { area: string; component: string; file: string; n: number }[] {
  const out: { area: string; component: string; file: string; n: number }[] = [];
  for (const area of readdirSync(variantsDir, { withFileTypes: true })) {
    if (!area.isDirectory()) continue;
    for (const name of readdirSync(join(variantsDir, area.name))) {
      const match = /^c-(.+)-(\d+)\.tsx$/.exec(name);
      if (!match?.[1] || !match[2]) continue;
      out.push({
        area: area.name,
        component: match[1],
        file: name.slice(0, -4),
        n: Number(match[2]),
      });
    }
  }
  return out.sort(
    (a, b) => a.area.localeCompare(b.area) || a.component.localeCompare(b.component) || a.n - b.n,
  );
}

export function renderRegistry(): string {
  const groups = new Map<string, string[]>();
  for (const item of listExamples()) {
    const key = `${item.area}|${item.component}`;
    const lines = groups.get(key) ?? [];
    lines.push(
      `      { name: '${item.file}', load: () => import('@smartapp/ui/variants/${item.area}/${item.file}') },`,
    );
    groups.set(key, lines);
  }
  const body = [...groups.entries()]
    .map(([key, lines]) => {
      const [area, component] = key.split('|');
      return `  {\n    area: '${area}',\n    component: '${component}',\n    items: [\n${lines.join('\n')}\n    ],\n  },`;
    })
    .join('\n');
  return `// Generated by tooling/scripts/kit-variants.ts. Do not edit by hand.
import type { ComponentType } from 'react';

export type KitVariant = {
  readonly name: string;
  readonly load: () => Promise<{ Pattern: ComponentType }>;
};

export type KitVariantGroup = {
  readonly area: string;
  readonly component: string;
  readonly items: readonly KitVariant[];
};

export const KIT_VARIANT_GROUPS: readonly KitVariantGroup[] = [
${body}
];
`;
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(target, renderRegistry());
  process.stdout.write(`Wrote ${listExamples().length} kit variants to ${target}\n`);
}
